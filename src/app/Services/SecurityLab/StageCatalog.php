    public static function find(string $code): array
    {
        foreach (self::all() as $stage) {
            if ($stage['code'] === $code) {
                return $stage;
            }
        }

        throw new InvalidArgumentException("Unknown stage code: {$code}");
    }

    public static function exists(string $code): bool
    {
        foreach (self::all() as $stage) {
            if ($stage['code'] === $code) {
                return true;
            }
        }

        return false;
    }

    public static function codes(): array
    {
        return array_map(fn (array $stage) => $stage['code'], self::all());
    }
}
